  const reverse = new Map(Object.entries(messages).map(([zh, en]) => [en, zh]));
  const storageKey = "sgate.admin.language";
  let current = typeof navigator !== "undefined" && /^en\b/i.test(navigator.language) ? "en" : "zh-CN";
  try {
    const saved = localStorage.getItem(storageKey);
    if (["zh-CN", "en"].includes(saved)) current = saved;

  } catch (_) {
    // Storage may be blocked; language switching still works for this page.
  }
  function t(text) {
    if (!text) return text || "";
    const source = reverse.get(text) || text;
    if (current === "zh-CN") return source;
    if (Object.hasOwn(messages, source)) return messages[source];
    // Server duration hints combine a unit description and the setting's zero-value rule.
    const parts = source.split(/(?<=。)\s+/);
    return parts.length > 1 ? parts.map(t).join(" ") : source;
  }

  // Keep a binding on the DOM element rather than in a global collection.
  // Removed rows can be collected; switching language preserves nested form inputs.
  function localText(element, render) {
    element.textContent = render();
    const node = element.firstChild;
    element._renderTranslation = () => {
      if (node && node.parentNode === element) node.nodeValue = render();
      else element.textContent = render();
    };
  }
  function localAttr(element, name, render) {
    if (!element._translationAttributes) element._translationAttributes = new Map();
    const update = () => element.setAttribute(name, render());
    element._translationAttributes.set(name, update);
    update();
  }
  let onChange = () => {};
  function setLanguage(language) {
    if (!["zh-CN", "en"].includes(language)) return;
    current = language;
    try {
      localStorage.setItem(storageKey, language);
    } catch (_) {}
    if (document.documentElement) document.documentElement.lang = language;
    document.querySelectorAll("*").forEach((element) => {
      element._renderTranslation?.();
      element._translationAttributes?.forEach((update) => update());
    });
    document.querySelectorAll("[data-language-picker]").forEach((picker) => {
      picker.value = language;
    });
    onChange();
  }
